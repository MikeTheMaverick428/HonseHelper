use anyhow::Result;
use il2cpp_runtime::ProcessInfo;

const XOR_KEY: u8 = 0x5A;

fn xdecode(encoded: &[u8], key: u8) -> String {
    encoded.iter().map(|&b| b ^ key).map(char::from).collect()
}

pub fn game_process_names() -> Vec<String> {
    const ENUM: &[&[u8]] = &[
        &[
            0x2f, 0x37, 0x3b, 0x37, 0x2f, 0x29, 0x2f, 0x37, 0x3f, 0x2a, 0x28, 0x3f, 0x2e, 0x2e,
            0x23, 0x3e, 0x3f, 0x28, 0x38, 0x23, 0x74, 0x3f, 0x22, 0x3f,
        ],
        &[
            0x0f, 0x37, 0x3b, 0x37, 0x2f, 0x29, 0x2f, 0x37, 0x3f, 0x0a, 0x28, 0x3f, 0x2e, 0x2e,
            0x23, 0x1e, 0x3f, 0x28, 0x38, 0x23, 0x74, 0x3f, 0x22, 0x3f,
        ],
        &[
            0x2f, 0x37, 0x3b, 0x37, 0x2f, 0x29, 0x2f, 0x37, 0x3f, 0x74, 0x3f, 0x22, 0x3f,
        ],
        &[0x2f, 0x37, 0x3b, 0x37, 0x2f, 0x29, 0x2f, 0x37, 0x3f],
        &[0x0f, 0x37, 0x3b, 0x37, 0x2f, 0x29, 0x2f, 0x37, 0x3f],
        &[
            0x2f, 0x37, 0x3b, 0x37, 0x2f, 0x29, 0x2f, 0x37, 0x3f, 0x05, 0x3d, 0x3b, 0x37, 0x3f,
        ],
    ];

    ENUM.iter().map(|e| xdecode(e, XOR_KEY)).collect()
}

pub fn find_game_process() -> Result<ProcessInfo> {
    let names = game_process_names();
    let name_refs: Vec<&str> = names.iter().map(|s| s.as_str()).collect();
    il2cpp_runtime::find_process_by_names(&name_refs)
}
